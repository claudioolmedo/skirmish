// Grammatical gender of the named entities, per locale — the
// event feed's participles agree with it (pt 'Casa construída',
// es 'Granja construida'); English ignores it.
const GENDERS = {
  'pt-BR': {
    building: { house: 'f', farm: 'f', barracks: 'm', lumber: 'm', mill: 'm', mining: 'm', range: 'm', stable: 'm', blacksmith: 'f', watchtower: 'f', outpost: 'm', market: 'm' },
    unit: { villager: 'm', townCenter: 'm', scout: 'f', militia: 'f', archer: 'm', sheep: 'f', boar: 'm', deer: 'm', manAtArms: 'm' },
  },
  es: {
    building: { house: 'f', farm: 'f', barracks: 'm', lumber: 'm', mill: 'm', mining: 'm', range: 'f', stable: 'm', blacksmith: 'f', watchtower: 'f', outpost: 'm', market: 'm' },
    unit: { villager: 'm', townCenter: 'm', scout: 'f', militia: 'f', archer: 'm', sheep: 'f', boar: 'm', deer: 'm', manAtArms: 'm' },
  },
};

export const STRINGS = { en: EN, 'pt-BR': PT_BR, es: ES };

/// The locale for a stored value / browser language: an exact
/// stored locale wins; otherwise pt* -> 'pt-BR', es* -> 'es',
/// anything else (or nothing) -> 'en'. Pure — unit-tested.
export function resolveLocale({ stored = null, nav = null } = {}) {
  if (stored && LOCALES.includes(stored)) return stored;
  const lang = String(nav || '').toLowerCase();
  if (lang.startsWith('pt')) return 'pt-BR';
  if (lang.startsWith('es')) return 'es';
  return 'en';
}

function storageGet(key) {
  try { return globalThis.localStorage ? globalThis.localStorage.getItem(key) : null; }
  catch { return null; }
}
function storageSet(key, value) {
  try { if (globalThis.localStorage) globalThis.localStorage.setItem(key, value); }
  catch { /* private mode — the choice just does not persist */ }
}

let currentLocale = resolveLocale({
  stored: storageGet(LOCALE_STORE_KEY),
  nav: typeof navigator !== 'undefined' ? navigator.language : null,
});

export function getLocale() {
  return currentLocale;
}

/// Switch the active locale (validated against LOCALES) and
/// persist it. Returns the locale actually in effect.
export function setLocale(loc) {
  if (LOCALES.includes(loc)) {
    currentLocale = loc;
    storageSet(LOCALE_STORE_KEY, loc);
  }
  return currentLocale;
}

/// Lookup in a specific locale, falling back to English, then to
/// the key itself. {name} placeholders interpolate from `vars`.
export function tIn(locale, key, vars = null) {
  const table = STRINGS[locale] || EN;
  let s = table[key];
  if (s === undefined) s = EN[key];
  if (s === undefined) return key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, name) => (
      vars[name] === undefined || vars[name] === null ? m : String(vars[name])
    ));
  }
  return s;
}

/// Lookup in the active locale.
export function t(key, vars = null) {
  return tIn(currentLocale, key, vars);
}

/// The grammatical gender ('m' | 'f') of a named entity in a
/// locale — kind is 'building' | 'unit', id the semantic id used
/// by the name keys (e.g. 'house', 'villager'). Defaults 'm'.
export function genderOf(locale, kind, id) {
  const g = GENDERS[locale];
  return (g && g[kind] && g[kind][id]) || 'm';
}

/// A cost string from [amount, resourceKey] parts, e.g.
/// costText([[50, 'food']]) -> '50 food' / '50 de comida'.
export function costText(parts, locale = currentLocale) {
  return parts
    .map(([n, res]) => tIn(locale, 'cost.part', { n, res: tIn(locale, 'res.' + res) }))
    .join(' · ');
}

